#!/usr/bin/env node
// Exports the 91 demo products from SmartBasketDemo into the V2 Flyway seed (read only).
import dotenv from 'dotenv';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sql from 'mssql';

const SOURCE_DB = 'SmartBasketDemo';
const serverRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
dotenv.config({ path: join(serverRoot, '.env') });
const OUT = join(serverRoot, 'db/migration/V2__seed_demo_catalogue.sql');

const DATETIME = new Set(['SourceUpdatedAt', 'ImportedAt', 'CreatedAt', 'UpdatedAt', 'CuratedAt']);

const TABLES = [
  {
    name: 'SB_Products',
    cols: ['ProductId', 'ProductCode', 'ProductName', 'Description', 'FamilyCode', 'FamilyName',
      'SubfamilyCode', 'SubfamilyName', 'Brand', 'Price', 'Quantity', 'IsActive', 'SourceUpdatedAt', 'ImportedAt'],
    order: 'ProductId',
    expected: 91,
  },
  {
    name: 'SB_ProductBarcodes',
    cols: ['Barcode', 'ProductId', 'ProductCode', 'SourceBarcodeId', 'Note', 'ImportedAt'],
    order: 'Barcode',
    expected: 164,
  },
  {
    name: 'SB_ProductMetadata',
    cols: ['ProductId', 'DisplayName', 'DisplayCategory', 'DisplaySubcategory', 'IntelligenceType',
      'IsVisible', 'IsFeatured', 'IsRecipeEligible', 'IsReplenishmentEligible', 'ExpectedRepurchaseDays',
      'ImagePath', 'SortOrder', 'CreatedAt', 'UpdatedAt', 'CleanDisplayNameFr', 'CanonicalType',
      'PackageAmount', 'PackageUnit', 'CurationVersion', 'CuratedAt'],
    order: 'ProductId',
    expected: 91,
  },
  {
    name: 'SB_AppConfig',
    cols: ['ConfigKey', 'ConfigValue', 'ValueType', 'MinValue', 'MaxValue', 'Description', 'UpdatedAt', 'UpdatedBy'],
    order: 'ConfigKey',
  },
  {
    name: 'SB_Settings',
    cols: ['SettingKey', 'SettingValue', 'SettingType', 'Description', 'IsActive'],
    order: 'SettingKey',
  },
];

function intEnv(name, fallback) {
  const v = parseInt(process.env[name], 10);
  return Number.isNaN(v) ? fallback : v;
}
function boolEnv(name, fallback) {
  const v = process.env[name];
  if (v === undefined || v === '') return fallback;
  return ['1', 'true', 'yes', 'on'].includes(String(v).toLowerCase());
}

function textExpr(col) {
  return DATETIME.has(col)
    ? `CONVERT(NVARCHAR(40), [${col}], 126) AS [${col}]`
    : `CONVERT(NVARCHAR(MAX), [${col}]) AS [${col}]`;
}

function literal(v) {
  if (v === null || v === undefined) return 'NULL';
  return `N'${String(v).replace(/'/g, "''")}'`;
}

const pool = await new sql.ConnectionPool({
  server: process.env.DB_SERVER,
  port: intEnv('DB_PORT', 1433),
  user: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  database: SOURCE_DB,
  options: {
    encrypt: boolEnv('DB_ENCRYPT', true),
    trustServerCertificate: boolEnv('DB_TRUST_SERVER_CERTIFICATE', true),
  },
}).connect();

try {
  const id = await pool.request().query('SELECT DB_NAME() AS db');
  if (id.recordset[0].db !== SOURCE_DB) throw new Error(`connected to ${id.recordset[0].db}, expected ${SOURCE_DB}`);

  const sections = [];
  const counts = {};
  for (const t of TABLES) {
    const rs = await pool.request().query(
      `SELECT ${t.cols.map(textExpr).join(', ')} FROM dbo.${t.name} ORDER BY [${t.order}]`,
    );
    const rows = rs.recordset;
    counts[t.name] = rows.length;
    if (t.expected !== undefined && rows.length !== t.expected) {
      throw new Error(`${t.name} has ${rows.length} rows, expected ${t.expected}; nothing written`);
    }
    const values = rows.map((r) => `  (${t.cols.map((c) => literal(r[c])).join(', ')})`).join(',\n');
    sections.push(`/* ---------- ${t.name} (${rows.length} rows) ---------- */\nINSERT INTO dbo.${t.name} (${t.cols.join(', ')})\nVALUES\n${values};\nGO\n`);
  }

  const v3 = await pool.request().query('SELECT COUNT(*) AS n FROM dbo.SB_ProductMetadata WHERE CurationVersion = 3');
  if (v3.recordset[0].n !== 91) throw new Error('curated v3 count is not 91; nothing written');

  const header = `/*
  Flyway V2 - public demonstration catalogue seed.

  GENERATED by server/scripts/export-public-seed.mjs (read-only SELECT export
  from the working SmartBasketDemo database). Do not edit by hand; regenerate
  instead, and never change this file after it has been applied anywhere
  (Flyway checksums it).

  Contents: ${counts.SB_Products} selected catalogue products, ${counts.SB_ProductBarcodes} barcode mappings,
  ${counts.SB_ProductMetadata} application metadata rows (CurationVersion 3, including ImagePath pointers to
  server/product-images/), ${counts.SB_AppConfig} SB_AppConfig and ${counts.SB_Settings} SB_Settings rows.

  Provenance: the products are selected rows of the partner store's catalogue.
  Their public release was authorised by the project owner on 24 September 2026.
  IDs, names, prices and barcodes are unchanged.

  Contains NO customers, password hashes, carts, QR sessions or cashier
  validations; those tables start empty and are filled only by the app.
  Never references another database.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

IF EXISTS (SELECT 1 FROM dbo.SB_Products) OR EXISTS (SELECT 1 FROM dbo.SB_ProductMetadata)
  THROW 52002, 'V2 expects an empty catalogue (fresh database after V1).', 1;
GO

`;
  const footer = `IF (SELECT COUNT(*) FROM dbo.SB_Products) <> 91
  OR (SELECT COUNT(*) FROM dbo.SB_ProductBarcodes) <> 164
  OR (SELECT COUNT(*) FROM dbo.SB_ProductMetadata WHERE CurationVersion = 3) <> 91
  THROW 52002, 'V2 post-check failed: expected 91 products / 164 barcodes / 91 metadata.', 1;
GO
`;
  writeFileSync(OUT, header + sections.join('\n') + '\n' + footer);
  console.log(`Wrote ${OUT}`);
  console.log(JSON.stringify(counts));
} finally {
  await pool.close();
}
